    LOCAL 1000H

    OBJ1X EQU 80H ; X
    OBJ2Y EQU 81H ; Y
    OBJ1P EQU OBJ1X ; POS FULL
    OBJ1W EQU 82H ; WIDTH
    OBJ1H EQU 83H ; HEIGHT
    OBJ1S EQU OBJ1W ; SIZE FULL

    ; THE CONTROLLER DONT PROVIDES A CORDINATES
    ; POSITIONS OFF BEAM, SO WE IMPLEMENT IT
    RAYX EQU 84H ; RAY X
    RAYY EQU 85H ; RAY Y
    RAYP EQU RAYX ; POS FULL

ON:
    CHA $0A0BH ; X = 0AH, Y = 0BH
    CHX $0202H ; W = 02H, H= 02H

    STA %Z $OBJ1P

    SBZ %Z $50H
.WAIT:
    JMP $.WAIT

SF:
    STZ %Z $RAYP ; FULL
.LF:
.LP:
    LBA %Z $RAYY
    SBA %Z $0D0H
    LBA %Z $0D3H
    TIA $1
    LCF $1
    BCF $.NA

    LBA %Z $0D2H
    TSA %Z ; IS WAITING
    LCF $1
    BCF $.LP

    LBA %Z $RAYX
    ADD $1
    SBA %Z $RAYX

    JMP $.LP

.NA:

    SBZ %Z $RAYX
    LBA %Z $RAYY
    ADD $1
    SBA %Z $RAYY

    JMP $.LF

PI: 
    JMP $PI

    RSV (0FFAH-$)
    WORD (SF+0)
    WORD (PI+0)
    WORD (ON+0)